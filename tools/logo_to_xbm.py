#!/usr/bin/env python3
"""Convert the Makera logo (PNG, white background) into a 1-bit XBM header for U8g2 (ticket #28).

Every non-white pixel (black and the blue stroke) becomes a lit OLED pixel, white stays off.
The content is cropped to its bounding box and scaled to fit MAX_W x MAX_H, keeping the aspect ratio.
Output format: XBM (rows padded to whole bytes, LSB = leftmost pixel), as expected by U8g2::drawXBMP.

Usage: python3 -I tools/logo_to_xbm.py <logo.png> src/logo_bitmap.h [preview.png]
Requires Pillow. The PNG is not in any repository. src/logo_bitmap.h (Makera trademark, private use only)
is committed in the private repository and left out of the public export by tools/strip_private.py
(ticket #50, DECISIONS.md 2026-11-11). Without it the firmware shows the neutral src/logo_fallback.h.
"""
import sys

from PIL import Image

MAX_W = 40
MAX_H = 40
PREVIEW_SCALE = 4


def ink(rgb):
    """0 = background, 255 = logo. Dark or strongly coloured pixels count as logo."""
    r, g, b = rgb
    lum = (299 * r + 587 * g + 114 * b) // 1000
    sat = max(r, g, b) - min(r, g, b)
    return 255 if lum < 128 or sat > 96 else 0


def main():
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    img = Image.open(src).convert("RGB")
    px = img.load()
    mask = Image.new("L", img.size)
    mp = mask.load()
    for y in range(img.height):
        for x in range(img.width):
            mp[x, y] = ink(px[x, y])
    box = mask.getbbox()
    if box is None:
        sys.exit("no logo pixels found")
    mask = mask.crop(box)
    w, h = mask.size
    scale = min(MAX_W / w, MAX_H / h)
    tw, th = max(1, round(w * scale)), max(1, round(h * scale))
    small = mask.resize((tw, th), Image.LANCZOS)
    bits = [[small.getpixel((x, y)) >= 128 for x in range(tw)] for y in range(th)]

    stride = (tw + 7) // 8
    data = []
    for row in bits:
        for bx in range(stride):
            v = 0
            for i in range(8):
                x = bx * 8 + i
                if x < tw and row[x]:
                    v |= 1 << i
            data.append(v)

    lines = [
        "#pragma once",
        "// Makera logo as 1-bit XBM for U8g2::drawXBMP (screensaver, ticket #28).",
        "// Generated by tools/logo_to_xbm.py; do not edit. Makera trademark: private use only.",
        "// Private repository only, never exported; without it the firmware uses src/logo_fallback.h (ticket #50).",
        "#include <cstdint>",
        "",
        "#include <pgmspace.h>",
        "",
        f"constexpr int LOGO_W = {tw};",
        f"constexpr int LOGO_H = {th};",
        "",
        "// Picture (# = lit):",
    ]
    lines += ["//   " + "".join("#" if b else "." for b in row) for row in bits]
    lines.append(f"static const uint8_t LOGO_XBM[{len(data)}] PROGMEM = {{")
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 12]) + ",")
    lines.append("};")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out}: {tw}x{th}, {len(data)} bytes")

    if len(sys.argv) == 4:
        # Preview as the OLED shows it: lit pixels white on black, scaled up.
        prev = Image.new("1", (tw, th))
        pp = prev.load()
        for y, row in enumerate(bits):
            for x, b in enumerate(row):
                pp[x, y] = 1 if b else 0
        prev = prev.resize((tw * PREVIEW_SCALE, th * PREVIEW_SCALE), Image.NEAREST)
        prev.save(sys.argv[3])
        print(f"preview: {sys.argv[3]}")


if __name__ == "__main__":
    main()
